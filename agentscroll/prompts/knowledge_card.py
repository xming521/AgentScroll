KNOWLEDGE_CARD_PROMPT = """
你会收到一个已标注为 `news` 或 `fun` 的中文互联网热点话题，以及围绕该话题采集到的正文、评论。只依据输入材料和随后提供的当前类别专用规则进行判断，不要联网、不要调用工具、不要读取文件，也不要用记忆补齐输入中没有的事实。目标是像真人一样记住近期“有这么个事或梗”和它的大致意思，不是整理完整报道或资料摘要。

如果证据已经表明话题不符合当前类别专用规则，将 `status` 设为 `rejected`。标题只是待核实的话题线索，不能单独作为成卡材料；`evidence` 为空时必须将 `status` 设为 `needs_research`。有证据时，只有连基本事件、梗或有趣之处都无法辨认才需要补搜；缺少精确日期、数字、完整经过、原因、责任归属或各方回应都不单独构成补搜理由。材料足以形成简短知识卡但不足以支持主动分享时，仍设为 `complete`，降低 `share_score` 并令 `share` 为 `null`。未核实细节必须保留来源限定，不得写成确定事实。

按现有材料给每个话题的即时分享价值打 0 至 10 的整数分：0 分表示当前材料不足或没有可用来源；1 至 3 分表示话题平常、过时或很难引发回应；4 至 6 分表示有一定谈资，但当前不足以支持主动分享；7 至 8 分表示新近、明确且值得立即分享；9 至 10 分仅用于符合当前类别专用规则中最高分标准的话题。
达到 7 分时，按当前类别专用规则填写分享内容。分享内容应让人知道大致内容，同时想点开原文看完整细节；不得使用材料不支持的夸张表达、伪造悬念或故意隐去改变内容性质的关键事实。分享还必须带一条评论，优先按当前类别专用规则选择现有真实评论；没有合适评论时，再以模仿真人的口吻按规则写一句简短的自然反应。

输入字段含义：

- `title`：需要理解的话题标题；
- `label`：第一轮确定的主要内容类型；
- `evidence`：已取得的真实帖子材料。每项包含平台、发布时间、正文和少量评论；`source_id` 是帖子编号，其评论包含当前话题内唯一的 `comment_id` 和网友原文 `text`。

只返回一个 JSON object，其中 `cards` 是只包含该话题一张卡的数组。卡片字段含义：

- `status`：`complete` 表示现有材料足以生成，`needs_research` 表示仍需补充调查，`rejected` 表示证据已足以确认话题不值得形成近期知识卡；
- `rejection_reason`：只有 `rejected` 时填写具体淘汰原因，不超过 30 个汉字；其他状态必须为空字符串；
- `knowledge`：按当前类别专用规则生成的一至两句简短记忆，不超过 80 个汉字；若不是 `complete` 则必须为空字符串；
- `chat_context`：按当前类别专用规则生成的聊天切入角度或使用语境，不超过 50 个汉字；若不是 `complete` 则必须为空字符串；
- `share_score`：按上述标准得出的 0 至 10 整数，每个话题都必须评分；状态不是 `complete` 或没有可选 `source_id` 时必须为 0；
- `share`：`share_score<7` 时必须为 `null`；`share_score>=7` 时为即时分享对象，其中：
  - `text`：要发送的大致内容或标题，应用真实具体的信息点产生点击原文的兴趣，不超过 50 个汉字；
  - `source_id`：按当前类别的选帖规则选中的一个 `evidence.source_id`；程序会据此回填真实 URL；
  - `comment_id`：从当前话题任一 `evidence.comments` 中选择的真实评论编号，不要求属于所选 `source_id`；不用真实评论时为空字符串；
  - `generated_comment`：没有合适真实评论时自拟的一句评论，不超过 20 个汉字；选择了 `comment_id` 时必须为空字符串。

`share_score>=7` 时，`share.text` 和 `share.source_id` 必须填写，`share.comment_id` 和 `share.generated_comment` 必须且只能填写一个。不要复制或改写真实评论文本，只返回它的 `comment_id`。

"""

