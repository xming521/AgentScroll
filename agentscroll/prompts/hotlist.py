"""Prompt for hot-list topic selection."""

HOTLIST_FIRST_PASS_PROMPT = """
你会收到一份当前中文互联网热榜快照，以及程序按标题相似度召回的少量历史事件标题。

这是第一轮粗筛和历史事件判断，不是事实核验。不要搜索互联网，不要打开 URL，不要调用工具，也不要依赖输入之外的事实。请从全部条目中选出最多 15 个最值得进入下一轮内容调研的话题；对值得选入且带 history 的话题，还要判断当前标题与历史标题是不是同一事件，以及是否出现实质新进展，并按 new、update、seen 分类。

输入 JSON 字段：

- candidates：当前热榜条目数组；source 是平台；history 为当前标题召回的可能相关历史标题数组。数组中 history_id 是历史事件的本轮临时编号，hours_ago 是历史标题距本轮约多少小时；可选的 recent_same_person=true 表示程序发现当前标题与该历史标题包含相同的明确人物名，且相距不超过 6 小时。

candidates 中，文本相似的当前标题会尽量相邻，方便比较；相邻不代表属于同一事件。

history 只表示可能相关，不代表一定是同一事件。相同的明确人物在数小时内连续出现，会提高其属于同一事件的可能性，应优先比较对应历史标题；但这只是疑似信号，人物相同、地点相同或主题相近本身仍不足以认定为同一事件，最终还要结合标题中的对象、动作和进展判断。

每个话题只能选择一个最主要的 label：

- news：可能影响较多人并具有现实公共价值的突发新闻；
- fun：包含新词、固定表达、人物梗、反差、抽象、猎奇、荒诞感或其他即时分享价值的内容。

不要为了数量选择普通、重复或没有调研价值的标题，也不要因为某个标题信息完整、容易解释就优先选择它。数量由符合条件的话题数量决定，不符合上述 news 或 fun 价值标准的标题不得选入。

标题中出现语义不明但新奇、反常、像黑话或像固定表达的短语，是进入下一轮查明来源和含义的正向信号，不是淘汰理由。普通明星动态、赛事对阵、产品宣传或泛泛提问，除非具有明显新意、公共影响或异常语境，否则降低优先级。

若发现多个标题明确属于同一事件，只输出一个代表条目，并把已识别出的其他编号放进 related_ids，避免同一事件重复占用话题名额。related_ids 不占上述类别容量。representative_id 只是话题分组锚点。选择 news 的代表条目时，优先使用简洁、直接陈述核心事件或最新关键进展的标题。选择 fun 的代表条目时，优先保留最能呈现原梗、反差或异常表达的原始标题。

同一个 history_id 代表同一个历史事件；它可能出现在多个候选项的 history 中，对应标题文字也可能不同。若多个当前标题都对应它，必须合并成同一个输出话题。

对本轮值得选入的话题，再与候选项 history 中的标题比较：

- new：不是同一事件，或仅凭标题不能确认是同一事件。放入 topics，relation 为 new，history_id 为 null；
- update：明确是同一事件，并且当前标题明确出现新的状态、结果、数字、处置或回应。放入 topics，relation 为 update，history_id 填对应历史标题编号；
- seen：明确是同一事件，但当前标题没有上述实质新进展。放入 seen，不再进入topics，history_id 填对应历史标题编号。

只返回一个 JSON object，包含 topics 和 seen 两个字段：

topics：选中的话题数组，最多 15 个；
- representative_id：该话题的分组锚点 id；按上述当前类别的代表条目规则选择；
- related_ids：与代表条目明确属于同一事件的其他输入编号，没有则为空数组；
- label：该话题最主要的筛选类别，只能是 news、fun 之一；
- relation：只能是 new 或 update；
- history_id：update 对应的历史标题编号；new 必须为 null。

seen：确认是没有实质新进展的重复历史事件数组；
- representative_id、related_ids、label：含义与 topics 相同；
- history_id：对应的历史标题编号。

不得返回输入中不存在的编号，不得让同一个编号出现在多个话题中，也不要返回任何额外字段。
"""

