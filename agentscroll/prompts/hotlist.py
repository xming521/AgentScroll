"""Prompt for hot-list topic selection."""

HOTLIST_FIRST_PASS_PROMPT = """
你会收到一份当前中文互联网热榜快照。

这是第一轮粗筛，不是事实核验。不要搜索互联网，不要打开 URL，不要调用工具，也不要依赖输入之外的事实。请从全部条目中选出最多 15 个最值得进入下一轮内容调研的话题。

每个话题只能选择一个最主要的 `label`：

- `news`：可能影响较多人并具有现实公共价值的突发新闻；
- `fun`：包含新词、固定表达、人物梗、反差、抽象、猎奇、荒诞感或其他即时分享价值的内容。

不要为了数量选择普通、重复或没有调研价值的标题，也不要因为某个标题信息完整、容易解释就优先选择它。数量由符合条件的话题数量决定，不符合上述 news 或 fun 价值标准的标题不得选入。

标题中出现语义不明但新奇、反常、像黑话或像固定表达的短语，是进入下一轮查明来源和含义的正向信号，不是淘汰理由。普通明星动态、赛事对阵、产品宣传或泛泛提问，除非具有明显新意、公共影响或异常语境，否则降低优先级。`source` 只用于理解平台语境和选择查询入口，不能作为内容质量或真实性的直接依据。

若发现多个标题明确属于同一事件，只输出一个代表条目，并把已识别出的其他编号放进 `related_ids`，避免同一事件重复占用话题名额；不要求找全所有平台变体。`related_ids` 不占上述类别容量。`representative_id` 只是话题分组锚点；同一话题只要存在非知乎条目，就必须选择非知乎条目。整组只有知乎条目时仍可选入，后续才把这些知乎标题用于生成其他平台的检索词。选择 `news` 的代表条目时，优先使用简洁、直接陈述核心事件或最新关键进展的标题。选择 `fun` 的代表条目时，优先保留最能呈现原梗、反差或异常表达的原始标题。

边界示例仅用于说明规则，不是需要模仿的关键词：
- “电子咸菜突然学会了请假”即使含义不清，只要表达反常且像新梗，也应作为 `fun` 候选进入调研；
- “某演员今日发布自拍”若没有其他异常语境，通常不应仅因人物知名而入选。

只返回一个 JSON object，包含 `topics` 字段：

`topics`：选中的话题数组，最多 15 个；
- `representative_id`：该话题的分组锚点 id；按上述当前类别的代表条目规则选择；
- `related_ids`：与代表条目明确属于同一事件的其他输入编号，没有则为空数组；
- `label`：该话题最主要的筛选类别，只能是 `news`、`fun` 之一；

不得返回输入中不存在的编号，不得让同一个编号出现在多个话题中，也不要返回任何额外字段。
"""

